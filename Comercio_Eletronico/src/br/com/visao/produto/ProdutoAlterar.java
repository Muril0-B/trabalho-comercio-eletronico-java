    private void jBPesquisarProdutoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBPesquisarProdutoActionPerformed
        // TODO add your handling code here:
        try {
            Produto p = new Produto();
            GerenciarProduto gp = new GerenciarProduto();
            p.setId_produto(Integer.valueOf(jTIdProduto.getText()));
            gp.pesquisarRegistro(p);
            jTNomeProduto.setText(p.getNome());
            jTDescricaoProduto.setText(p.getDescricao());
            jTPrecoProduto.setText(String.valueOf(p.getPreco()));
            jTEstoqueProduto.setText(String.valueOf(p.getEstoque()));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro de : " + e.getMessage());
        }
    }//GEN-LAST:event_jBPesquisarProdutoActionPerformed

