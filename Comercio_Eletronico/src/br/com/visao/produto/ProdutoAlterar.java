    private void jBAlterarProdutoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBAlterarProdutoActionPerformed
        // TODO add your handling code here:
       try {
        Produto p = new Produto();
        GerenciarProduto gp = new GerenciarProduto();
        p.setId_produto(Integer.valueOf(jTIdProduto.getText()));
        p.setNome(jTNomeProduto.getText());
        p.setDescricao(jTDescricaoProduto.getText());
        p.setPreco(Double.parseDouble(jTPrecoProduto.getText().replace(",", ".")));
        p.setEstoque(Integer.valueOf(jTEstoqueProduto.getText()));
        gp.editarProduto(p);

        jTIdProduto.setText("");
        jTNomeProduto.setText("");
        jTDescricaoProduto.setText("");
        jTPrecoProduto.setText("");
        jTEstoqueProduto.setText("");
        jTIdProduto.requestFocus();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro de : " + e.getMessage());
    }
    }//GEN-LAST:event_jBAlterarProdutoActionPerformed

