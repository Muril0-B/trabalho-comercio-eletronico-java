    private void jBpesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBpesquisarActionPerformed
        // TODO add your handling code here:
         try{
        Pagamento p = new Pagamento();
        GerenciarPagamento gp = new GerenciarPagamento();
         p.setIdPagamento(Integer.valueOf(jTpagamento.getText()));
         gp.pesquisarRegistro(p);
         jTpedido.setText(String.valueOf(p.getIdPedido()));
         jTvalorPago.setText(String.valueOf(p.getValorPago()));
         jTformaPagamento.setText(p.getFormaPagamento());
         jTstatusPagamento.setText(p.getStatusPagamento());
         jTpagamento.setEditable(false);
       }
       catch (Exception e){
                System.out.println("Erro " + e.getMessage());
       }
    }//GEN-LAST:event_jBpesquisarActionPerformed

    private void jBalterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBalterarActionPerformed
        // TODO add your handling code here:
        try{
            Pagamento p = new Pagamento();
            GerenciarPagamento gp = new GerenciarPagamento();
            p.setIdPagamento(Integer.valueOf(jTpagamento.getText()));
            p.setIdPedido(Integer.valueOf(jTpedido.getText()));
            p.setValorPago(Double.valueOf(jTvalorPago.getText()));
            p.setFormaPagamento(jTformaPagamento.getText());
            p.setStatusPagamento(jTformaPagamento.getText());
            gp.alterar(p);
      
            jTvalorPago.setText("");
            jTformaPagamento.setText("");
            jTstatusPagamento.setText("");
            jTpedido.setText("");
            jTpedido.requestFocus();
            }catch (Exception e){
                JOptionPane.showMessageDialog(this,"Erro de : " + e.getMessage());
            }
    }//GEN-LAST:event_jBalterarActionPerformed

