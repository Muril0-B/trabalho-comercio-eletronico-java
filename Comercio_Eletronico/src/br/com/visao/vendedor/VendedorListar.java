    private void jBBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBBuscarActionPerformed
        // TODO add your handling code here:
        try{
            Vendedor v = new Vendedor();
            GerenciarVendedor gv = new GerenciarVendedor();
            DefaultTableModel pesquisarcliente = (DefaultTableModel) jTVendedor.getModel ();
            if(jTIdVendedor.getText().equalsIgnoreCase("")){
                ArrayList<Vendedor> vendedor = gv.pesquisarTudo();
                for (int i = 0; i<vendedor.size(); i++){
                    v = vendedor.get(i);
                    pesquisarcliente.addRow(new Object[]{v.getId_vendedor(), v.getNome(), v.getEmail(), v.getTelefone(), v.getPercentual_comissao()});
                }
            } else{
                v.setId_vendedor(Integer.valueOf(jTIdVendedor.getText()));
                gv.pesquisarRegistro(v);
                pesquisarcliente.addRow(new Object[]{v.getId_vendedor(), v.getNome(), v.getEmail(), v.getTelefone(), v.getPercentual_comissao()});
            }

            jTIdVendedor.setText(null);
            jTIdVendedor.requestFocus();
        } catch (Exception e){
            JOptionPane.showMessageDialog(null, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jBBuscarActionPerformed

